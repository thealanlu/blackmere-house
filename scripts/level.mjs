import {writeFile} from 'node:fs/promises';
import {Scene} from '../dist/vendor/three.module.js';
import {createWorld} from '../dist/src/world.js';

for(const [file,legacy,expanded] of [['level-data.js',false,true],['level-v4.js',false,false],['level-legacy.js',true,false]]) {
  const world=createWorld(new Scene(),{legacy,expanded});
  const {objects,solid}=world;
  const level={
    solid,
    objects:objects.map(o=>{
      const {kind,id,name,body,x,y,z,axis,secret,type,anchor,yaw,view,peek,exit,look,spawn}=o;
      return {kind,id,name,body,x,y,z,axis,secret,type,anchor,yaw,view,peek,exit,look,spawn,
        blocker:o.blocker ? solid.indexOf(o.blocker) : undefined,
        drawerAngle:o.drawer?.parent.rotation.y, panels:o.panels?true:undefined};
    }),
    itemSpots:Object.fromEntries(Object.entries(world.itemSpots).map(([id,spots])=>
      [id,spots.map(s=>s.kind?objects.indexOf(s):{x:s.x,y:s.y,z:s.z})])),
    gate:solid.indexOf(world.gateBlock)
  };
  if(!legacy) {
    level.walls=world.walls;
    level.passages=world.passages.map(({door,...portal})=>({...portal,index:door?objects.indexOf(door):null}));
  }
  if(expanded)Object.assign(level,{expanded,nightmareSpots:world.nightmareSpots});
  await writeFile(new URL('../dist/src/'+file,import.meta.url),
    '// Generated by scripts/level.mjs from the mansion geometry.\nexport default '+JSON.stringify(level)+';\n');
}
